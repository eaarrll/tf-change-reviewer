/*
 * Generates eval fixtures from Terraform scenarios with REAL provider plans, offline.
 *
 * A scenario is evals/scenarios/<name>/{before/, after/, labels.json}: the repository before and after
 * the pull request. For each scenario this script:
 *
 *   1. copies both trees to evals/.work/<name>/ and adds a provider override with mock credentials
 *      and every skip_* flag, so no AWS API is ever called;
 *   2. plans `before` with -refresh=false (all creates) and turns that plan into a state file,
 *      filling every unknown computed value with a placeholder from the provider schema;
 *   3. plans `after` against that state, so the plan is the provider's real diff logic
 *      (replace_paths, action_reason, sensitive marks) for the change the PR makes;
 *   4. writes evals/fixtures/<name>/{plan.json, plan.txt, pr.diff, labels.json, repo/}.
 *
 * Usage: npm run gen-fixtures [-- <scenario> ...]   (needs terraform on PATH and network for the
 * first provider download; providers are cached in .tf-plugin-cache/).
 */
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseLabels, type Labels } from "./grade.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCENARIOS = join(ROOT, "evals", "scenarios");
const FIXTURES = join(ROOT, "evals", "fixtures");
const WORK = join(ROOT, "evals", ".work");
// Shared provider cache: run one generation at a time (concurrent `terraform init` runs rewrite the cached binary).
const PLUGIN_CACHE = process.env.TF_PLUGIN_CACHE_DIR ?? join(ROOT, ".tf-plugin-cache");

/** Merged into the scenario's own `provider "aws"` block in the work copy only (Terraform override file). */
const MOCK_OVERRIDE = `# Generated by evals/gen-fixtures.ts: offline planning with mock credentials.
provider "aws" {
  access_key                  = "mock_access_key"
  secret_key                  = "mock_secret_key"
  skip_credentials_validation = true
  skip_requesting_account_id  = true
  skip_metadata_api_check     = true
  skip_region_validation      = true
}
`;

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
// Terraform JSON is loosely typed; this script only reshapes it.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type JsonObject = Record<string, any>;

interface SchemaBlock {
  attributes?: Record<string, { type?: Json; nested_type?: unknown }>;
  block_types?: Record<string, { nesting_mode: string; block: SchemaBlock }>;
}

/** Optional evals/scenarios/<name>/scenario.json. */
interface ScenarioOptions {
  /** -var values given only to the AFTER plan: simulates values injected outside the repo (CI TF_VAR_*). */
  afterVars?: Record<string, string>;
}

function tf(args: string[], cwd: string): string {
  const result = spawnSync("terraform", args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 512 * 1024 * 1024,
    env: { ...process.env, TF_PLUGIN_CACHE_DIR: PLUGIN_CACHE, TF_IN_AUTOMATION: "1", TF_INPUT: "0" },
  });
  if (result.status !== 0) {
    throw new Error(`terraform ${args.join(" ")} failed in ${cwd}:\n${result.stdout}\n${result.stderr}`);
  }
  return result.stdout;
}

function prepare(src: string, dest: string): void {
  rmSync(dest, { recursive: true, force: true });
  cpSync(src, dest, { recursive: true });
  writeFileSync(join(dest, "zz_mock_provider_override.tf"), MOCK_OVERRIDE);
}

/** A placeholder of the right type for an unknown computed value. */
/** Optional+computed attributes that the API leaves empty unless they were set (e.g. restore-only inputs). */
const EMPTY_WHEN_UNSET = new Set(["snapshot_identifier"]);

function placeholder(type: Json | undefined, name: string, address: string): Json {
  if (EMPTY_WHEN_UNSET.has(name)) return null;
  if (type === "string") {
    if (name === "arn") return `arn:aws:mock:eu-west-1:123456789012:${address}`;
    return `mock-${name}`;
  }
  if (type === "number") return 0;
  if (type === "bool") return false;
  if (Array.isArray(type)) {
    if (type[0] === "list" || type[0] === "set") return [];
    if (type[0] === "map") return {};
    if (type[0] === "object") return {};
  }
  return null;
}

/** Replace every `true` leaf of after_unknown with a typed placeholder, recursing into nested blocks. */
function fillUnknown(value: Json, unknown: Json, block: SchemaBlock | undefined, address: string): Json {
  if (unknown === true) return value ?? null;
  if (!unknown || typeof unknown !== "object" || Array.isArray(unknown)) return value;
  const obj: JsonObject = value && typeof value === "object" && !Array.isArray(value) ? { ...value } : {};
  for (const [key, u] of Object.entries(unknown)) {
    const attr = block?.attributes?.[key];
    const nested = block?.block_types?.[key];
    if (u === true) {
      obj[key] = attr ? placeholder(attr.type, key, address) : nested ? [] : `mock-${key}`;
    } else if (Array.isArray(u)) {
      const current = Array.isArray(obj[key]) ? (obj[key] as Json[]) : [];
      obj[key] = current.map((item, i) => fillUnknown(item, u[i] ?? null, nested?.block, address));
    } else if (u && typeof u === "object") {
      obj[key] = fillUnknown(obj[key] ?? null, u, nested?.block, address);
    }
  }
  return obj;
}

/** after_sensitive → state v4 sensitive_attributes paths. */
function sensitivePaths(marks: Json, path: JsonObject[] = [], out: JsonObject[][] = []): JsonObject[][] {
  if (marks === true) out.push(path);
  else if (Array.isArray(marks))
    marks.forEach((m, i) =>
      sensitivePaths(m, [...path, { type: "index", value: { value: i, type: "number" } }], out),
    );
  else if (marks && typeof marks === "object")
    for (const [k, m] of Object.entries(marks))
      sensitivePaths(m, [...path, { type: "get_attr", value: k }], out);
  return out;
}

/** Build a v4 state file from a create-only plan, as if that plan had been applied. */
function stateFromPlan(plan: JsonObject, schema: JsonObject): JsonObject {
  const providerSchemas = schema.provider_schemas as Record<
    string,
    { resource_schemas: Record<string, { version: number; block: SchemaBlock }> }
  >;
  const resources: JsonObject[] = [];
  for (const rc of (plan.resource_changes as JsonObject[]) ?? []) {
    if (rc.mode !== "managed") continue;
    const change = rc.change as JsonObject;
    const actions = change.actions as string[];
    if (actions.join() !== "create") {
      throw new Error(`before-plan must only create resources, but ${rc.address} is ${actions.join("+")}`);
    }
    const rs = providerSchemas[rc.provider_name as string]?.resource_schemas[rc.type as string];
    if (!rs) throw new Error(`no schema for ${rc.provider_name} ${rc.type}`);
    const attrs = fillUnknown(
      change.after,
      change.after_unknown,
      rs.block,
      rc.address as string,
    ) as JsonObject;
    if (attrs.id === null || attrs.id === undefined || attrs.id === "mock-id")
      attrs.id = `mock-${String(rc.address)}`;
    const module = (rc.module_address as string | undefined) ?? undefined;
    let res = resources.find((r) => r.type === rc.type && r.name === rc.name && r.module === module);
    if (!res) {
      res = {
        ...(module && { module }),
        mode: "managed",
        type: rc.type,
        name: rc.name,
        provider: `provider["${String(rc.provider_name)}"]`,
        instances: [],
      };
      resources.push(res);
    }
    (res.instances as JsonObject[]).push({
      ...(rc.index !== undefined && { index_key: rc.index }),
      schema_version: rs.version,
      attributes: attrs,
      sensitive_attributes: sensitivePaths(change.after_sensitive ?? {}),
    });
  }
  return {
    version: 4,
    terraform_version: plan.terraform_version as string,
    serial: 1,
    lineage: "00000000-0000-4000-8000-000000000001",
    outputs: {},
    resources,
    check_results: null,
  };
}

/** Known values of `after` over `old`; unknown leaves keep the old (placeholder) value. */
function mergeKnown(old: Json, after: Json, unknown: Json): Json {
  if (unknown === true) return old;
  if (Array.isArray(after)) {
    const u = Array.isArray(unknown) ? unknown : [];
    const o = Array.isArray(old) ? old : [];
    return after.map((v, i) => mergeKnown(o[i] ?? null, v, u[i] ?? false));
  }
  if (after && typeof after === "object") {
    const u =
      unknown && typeof unknown === "object" && !Array.isArray(unknown) ? (unknown as JsonObject) : {};
    const o = old && typeof old === "object" && !Array.isArray(old) ? (old as JsonObject) : {};
    const out: JsonObject = { ...o };
    for (const [k, v] of Object.entries(after)) out[k] = mergeKnown(o[k] ?? null, v, u[k] ?? false);
    for (const [k, uk] of Object.entries(u)) if (!(k in after) && uk === true) out[k] = o[k] ?? null;
    return out;
  }
  return after;
}

/** Every `references` entry under a configuration expression tree. */
function collectRefs(node: unknown, out: string[] = []): string[] {
  if (Array.isArray(node)) node.forEach((n) => collectRefs(n, out));
  else if (node && typeof node === "object")
    for (const [k, v] of Object.entries(node as JsonObject)) {
      if (k === "references" && Array.isArray(v)) out.push(...(v as string[]));
      else collectRefs(v, out);
    }
  return out;
}

/** Config address (resource or module call) → the config addresses it references. */
function configDeps(config: JsonObject): Map<string, Set<string>> {
  const deps = new Map<string, Set<string>>();
  const norm = (ref: string, prefix: string): string | null => {
    const parts = ref.split(".");
    if (["var", "local", "each", "count", "path", "terraform", "self"].includes(parts[0] ?? "")) return null;
    const n = parts[0] === "data" ? 3 : 2;
    return prefix + parts.slice(0, n).join(".").replace(/\[.*$/, "");
  };
  const walk = (mod: JsonObject | undefined, prefix: string): void => {
    for (const r of (mod?.resources as JsonObject[] | undefined) ?? []) {
      const refs = collectRefs([r.expressions, r.count_expression, r.for_each_expression]);
      deps.set(
        prefix + String(r.address),
        new Set(refs.map((x) => norm(x, prefix)).filter((x) => x !== null)),
      );
    }
    for (const [name, call] of Object.entries((mod?.module_calls as JsonObject | undefined) ?? {})) {
      const c = call as JsonObject;
      const refs = collectRefs([c.expressions, c.count_expression, c.for_each_expression]);
      deps.set(
        `${prefix}module.${name}`,
        new Set(refs.map((x) => norm(x, prefix)).filter((x) => x !== null)),
      );
      walk(c.module as JsonObject, `${prefix}module.${name}.`);
    }
  };
  walk(config.root_module as JsonObject, "");
  return deps;
}

/** Failing config addresses plus everything that depends on them (directly, via modules or data sources). */
function dependents(failing: Set<string>, deps: Map<string, Set<string>>): Set<string> {
  const out = new Set(failing);
  const hit = (ref: string): boolean => [...out].some((x) => x === ref || x.startsWith(ref + "."));
  for (let changed = true; changed;) {
    changed = false;
    for (const [addr, refs] of deps) {
      if (out.has(addr)) continue;
      const inExcludedModule = [...out].some((x) => x.startsWith("module.") && addr.startsWith(x + "."));
      if (inExcludedModule || [...refs].some(hit)) {
        out.add(addr);
        changed = true;
      }
    }
  }
  return out;
}

function instanceAddress(r: JsonObject, i: JsonObject): string {
  const key = i.index_key as string | number | undefined;
  const idx = key === undefined ? "" : typeof key === "number" ? `[${key}]` : `[${JSON.stringify(key)}]`;
  return `${r.module ? `${String(r.module)}.` : ""}${String(r.type)}.${String(r.name)}${idx}`;
}

/**
 * Placeholders for values that reference other resources (subnet_id = aws_subnet.x.id) do not match the
 * referenced resource's placeholder. Re-plan the before config against the state and copy the now-known
 * values in, until the before config plans clean. Resources whose plan calls the AWS API (and fails with
 * mock credentials) are left out with their dependents via -target.
 */
function converge(state: JsonObject, dir: string, config: JsonObject): JsonObject {
  const statePath = join(dir, "terraform.tfstate");
  const deps = configDeps(config);
  const failing = new Set<string>();
  let excluded = new Set<string>();
  for (let round = 0; round < 10; round++) {
    writeFileSync(statePath, JSON.stringify(state, null, 2));
    const targets = failing.size
      ? (state.resources as JsonObject[])
          .filter(
            (r) =>
              !excluded.has(`${r.module ? `${String(r.module)}.` : ""}${String(r.type)}.${String(r.name)}`),
          )
          .flatMap((r) => (r.instances as JsonObject[]).map((i) => `-target=${instanceAddress(r, i)}`))
      : [];
    if (failing.size && !targets.length) break;
    try {
      tf(
        [
          "plan",
          "-refresh=false",
          "-input=false",
          "-no-color",
          "-lock=false",
          ...targets,
          "-out=converge.out",
        ],
        dir,
      );
    } catch (error) {
      const found = [...(error as Error).message.matchAll(/^\s+with ([^,]+),$/gm)].map((m) =>
        (m[1] ?? "").replace(/\[[^\]]*\]/g, ""),
      );
      const fresh = found.filter((f) => !failing.has(f));
      if (!fresh.length) {
        console.error(`converge: plan failed in ${dir}; keeping state as is`);
        break;
      }
      fresh.forEach((f) => failing.add(f));
      excluded = dependents(failing, deps);
      console.error(`converge: leaving out ${[...excluded].join(", ")}`);
      continue;
    }
    const p = JSON.parse(tf(["show", "-json", "converge.out"], dir)) as JsonObject;
    const pending = ((p.resource_changes as JsonObject[]) ?? []).filter(
      (rc) => rc.mode === "managed" && ((rc.change as JsonObject).actions as string[]).join() !== "no-op",
    );
    if (!pending.length) break;
    for (const rc of pending) {
      const module = (rc.module_address as string | undefined) ?? undefined;
      const res = (state.resources as JsonObject[]).find(
        (r) => r.type === rc.type && r.name === rc.name && r.module === module,
      );
      const inst = (res?.instances as JsonObject[] | undefined)?.find((i) => i.index_key === rc.index);
      if (!inst) continue;
      const change = rc.change as JsonObject;
      inst.attributes = mergeKnown(
        inst.attributes as Json,
        change.after as Json,
        change.after_unknown as Json,
      );
    }
  }
  rmSync(statePath, { force: true });
  return state;
}

function listFiles(dir: string, base = dir): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    if (name === ".terraform" || name.startsWith("terraform.tfstate") || name.endsWith(".out")) continue;
    if (name === ".terraform.lock.hcl" || name.startsWith("zz_mock_")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full, base));
    else out.push(relative(base, full));
  }
  return out.sort();
}

function copyTree(src: string, dest: string): void {
  for (const file of listFiles(src)) {
    mkdirSync(dirname(join(dest, file)), { recursive: true });
    cpSync(join(src, file), join(dest, file));
  }
}

/** The PR diff, as `git diff` between the two trees with repo-relative a/ b/ paths. */
function prDiff(name: string, beforeDir: string, afterDir: string): string {
  const tmp = join(WORK, name, "_diff");
  rmSync(tmp, { recursive: true, force: true });
  copyTree(beforeDir, join(tmp, "a"));
  copyTree(afterDir, join(tmp, "b"));
  const result = spawnSync(
    "git",
    ["diff", "--no-index", "--no-color", "--unified=3", "--find-renames", "a", "b"],
    {
      cwd: tmp,
      encoding: "utf8",
    },
  );
  if (result.status !== 0 && result.status !== 1) throw new Error(`git diff failed: ${result.stderr}`);
  // Paths come out as a/a/x and b/b/x (a/a/x on both sides for deletions, b/b/x for additions): drop the tree prefix.
  return result.stdout
    .replace(/^(diff --git a\/|--- a\/|\+\+\+ b\/)([ab])\//gm, "$1")
    .replace(/^(diff --git \S+) b\/[ab]\//gm, "$1 b/")
    .replace(/^(rename (?:from|to)|copy (?:from|to)) [ab]\//gm, "$1 ");
}

/** Added (new-file numbering) and removed (old-file numbering) lines per file, from a unified diff. */
function diffLines(diff: string): { added: Map<string, Set<number>>; removed: Map<string, Set<number>> } {
  const added = new Map<string, Set<number>>();
  const removed = new Map<string, Set<number>>();
  let oldFile: string | null = null;
  let newFile: string | null = null;
  let oldLine = 0;
  let newLine = 0;
  const add = (m: Map<string, Set<number>>, f: string, l: number): void => {
    if (!m.has(f)) m.set(f, new Set());
    m.get(f)!.add(l);
  };
  for (const text of diff.split("\n")) {
    if (text.startsWith("--- ")) {
      oldFile = text === "--- /dev/null" ? null : text.slice(6);
    } else if (text.startsWith("+++ ")) {
      newFile = text === "+++ /dev/null" ? null : text.slice(6);
    } else if (text.startsWith("@@")) {
      const m = /^@@ -(\d+)(?:,\d+)? \+(\d+)/.exec(text);
      oldLine = Number(m?.[1] ?? 0);
      newLine = Number(m?.[2] ?? 0);
    } else if (text.startsWith("+")) {
      if (newFile) add(added, newFile, newLine);
      newLine++;
    } else if (text.startsWith("-")) {
      if (oldFile) add(removed, oldFile, oldLine);
      oldLine++;
    } else if (text.startsWith(" ")) {
      oldLine++;
      newLine++;
    }
  }
  return { added, removed };
}

function validateLabels(
  name: string,
  labels: Labels,
  plan: JsonObject,
  repoDir: string,
  diff: string,
): string[] {
  const problems: string[] = [];
  const { added, removed } = diffLines(diff);
  const changed = new Set(
    ((plan.resource_changes as JsonObject[]) ?? [])
      .filter((rc) => ((rc.change as JsonObject).actions as string[]).join() !== "no-op")
      .map((rc) => rc.address as string),
  );
  for (const m of labels.material) {
    if (!changed.has(m.address))
      problems.push(`${name}: labeled address ${m.address} is not a change in the plan`);
    for (const c of m.cause ?? []) {
      if (c.side === "base") {
        if (!removed.get(c.file)?.has(c.line))
          problems.push(`${name}: base-side cause ${c.file}:${c.line} is not a removed line in pr.diff`);
        continue;
      }
      const file = join(repoDir, c.file);
      if (!existsSync(file)) problems.push(`${name}: cause file ${c.file} does not exist`);
      else if (c.line < 1 || c.line > readFileSync(file, "utf8").split("\n").length)
        problems.push(`${name}: cause ${c.file}:${c.line} is out of range`);
      else if (!added.get(c.file)?.has(c.line))
        problems.push(`${name}: cause ${c.file}:${c.line} is not an added line in pr.diff`);
    }
  }
  for (const a of labels.acceptable ?? []) {
    if (!changed.has(a)) problems.push(`${name}: acceptable address ${a} is not a change in the plan`);
  }
  return problems;
}

function generate(name: string): string[] {
  const scenario = join(SCENARIOS, name);
  const work = join(WORK, name);
  const out = join(FIXTURES, name);
  mkdirSync(work, { recursive: true });
  mkdirSync(PLUGIN_CACHE, { recursive: true });

  const before = join(work, "before");
  const after = join(work, "after");
  prepare(join(scenario, "before"), before);
  prepare(join(scenario, "after"), after);

  tf(["init", "-input=false", "-no-color", "-backend=false"], before);
  tf(["plan", "-refresh=false", "-input=false", "-no-color", "-lock=false", "-out=before.out"], before);
  const beforePlan = JSON.parse(tf(["show", "-json", "before.out"], before)) as JsonObject;
  const schema = JSON.parse(tf(["providers", "schema", "-json"], before)) as JsonObject;
  const state = converge(stateFromPlan(beforePlan, schema), before, beforePlan.configuration as JsonObject);
  writeFileSync(join(after, "terraform.tfstate"), JSON.stringify(state, null, 2));

  const optionsPath = join(scenario, "scenario.json");
  const options = (
    existsSync(optionsPath) ? JSON.parse(readFileSync(optionsPath, "utf8")) : {}
  ) as ScenarioOptions;
  const vars = Object.entries(options.afterVars ?? {}).flatMap(([k, v]) => ["-var", `${k}=${v}`]);

  tf(["init", "-input=false", "-no-color", "-backend=false"], after);
  const planText = tf(
    ["plan", "-refresh=false", "-input=false", "-no-color", "-lock=false", ...vars, "-out=after.out"],
    after,
  );
  const plan = JSON.parse(tf(["show", "-json", "after.out"], after)) as JsonObject;

  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "plan.json"), JSON.stringify(plan, null, 1) + "\n");
  writeFileSync(join(out, "plan.txt"), planText);
  const diff = prDiff(name, join(scenario, "before"), join(scenario, "after"));
  writeFileSync(join(out, "pr.diff"), diff);
  copyTree(join(scenario, "after"), join(out, "repo"));
  // The raw JSON is copied (key order kept); parseLabels rejects a malformed file before that.
  const rawLabels = JSON.parse(readFileSync(join(scenario, "labels.json"), "utf8")) as unknown;
  const labels: Labels = parseLabels(rawLabels);
  writeFileSync(join(out, "labels.json"), JSON.stringify(rawLabels, null, 2) + "\n");
  if (options.afterVars) writeFileSync(join(out, "scenario.json"), JSON.stringify(options, null, 2) + "\n");

  const counts: Record<string, number> = {};
  for (const rc of (plan.resource_changes as JsonObject[]) ?? []) {
    const key = ((rc.change as JsonObject).actions as string[]).join("+");
    counts[key] = (counts[key] ?? 0) + 1;
  }
  const lines = planText.split("\n").length;
  console.log(
    `${name}: ${lines} plan lines, ${JSON.stringify(counts)}, ${labels.material.length} labeled material`,
  );
  return validateLabels(name, labels, plan, join(out, "repo"), diff);
}

const requested = process.argv.slice(2);
const names = requested.length
  ? requested
  : readdirSync(SCENARIOS).filter((n) => existsSync(join(SCENARIOS, n, "labels.json")));
const problems: string[] = [];
for (const name of names) {
  try {
    problems.push(...generate(name));
  } catch (error) {
    problems.push(`${name}: ${(error as Error).message}`);
  }
}
if (problems.length) {
  console.error(`\n${problems.length} problem(s):\n- ${problems.join("\n- ")}`);
  process.exitCode = 1;
}
