// Bundles the Action (src/main.ts → dist/index.js) and the CLI (src/cli.ts → dist/cli.js) into
// single ESM files for node24, and writes the license texts of every bundled third-party package
// to dist/licenses.txt.
import { chmodSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

// Some transitive dependencies are CommonJS and call require(); give them one.
const REQUIRE_SHIM =
  "import { createRequire as __tfcrCreateRequire } from 'node:module'; const require = __tfcrCreateRequire(import.meta.url);";

const common = {
  bundle: true,
  platform: "node",
  target: "node24",
  format: "esm",
  minify: false,
  sourcemap: false,
  // Notices are collected into dist/licenses.txt instead of being scattered through the bundle.
  legalComments: "none",
  metafile: true,
  banner: { js: REQUIRE_SHIM },
  logLevel: "info",
};

mkdirSync("dist", { recursive: true });
const action = await build({ ...common, entryPoints: ["src/main.ts"], outfile: "dist/index.js" });
const cli = await build({ ...common, entryPoints: ["src/cli.ts"], outfile: "dist/cli.js" });

// The CLI must start with its shebang (esbuild puts the banner first), and be executable.
const cliPath = "dist/cli.js";
const cliText = readFileSync(cliPath, "utf8").replace(/^#!.*\n/m, "");
writeFileSync(cliPath, `#!/usr/bin/env node\n${cliText}`);
chmodSync(cliPath, 0o755);

const inputs = new Set([...Object.keys(action.metafile.inputs), ...Object.keys(cli.metafile.inputs)]);
writeFileSync("dist/licenses.txt", thirdPartyNotices([...inputs]));

/** One section per bundled package: name, version, license id, then its LICENSE/NOTICE files verbatim. */
function thirdPartyNotices(inputs) {
  const roots = new Set();
  for (const input of inputs) {
    const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (match) roots.add(match[1]);
  }
  const sections = [...roots]
    .map((root) => {
      const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
      const files = readdirSync(root).filter((name) => /^(licen[cs]e|notice|copying)/i.test(name));
      const texts = files.map((name) => readFileSync(join(root, name), "utf8").trim());
      const license = typeof pkg.license === "string" ? pkg.license : "see text";
      return {
        id: `${pkg.name}@${pkg.version}`,
        body: `${pkg.name}@${pkg.version} (${license})\n\n${texts.join("\n\n") || "(no license file shipped; license field: " + license + ")"}`,
      };
    })
    .sort((a, b) => a.id.localeCompare(b.id));
  // Several nested copies of one package version would repeat the same text.
  const unique = sections.filter((s, i) => i === 0 || s.id !== sections[i - 1].id);
  const header =
    "Third-party software bundled into dist/index.js and dist/cli.js by tf-change-reviewer.\n" +
    "Generated by scripts/build.mjs; do not edit.\n";
  return [header, ...unique.map((s) => s.body)].join("\n" + "=".repeat(78) + "\n\n") + "\n";
}
